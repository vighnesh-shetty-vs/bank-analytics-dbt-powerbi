"""Run the compiled dbt analyses and write their results to docs/business_questions.md.

Run `dbt compile` first; this script executes target/compiled/.../analyses/*.sql against
data/bank.duckdb so every number in the docs comes from the same models the tests cover.
Also exports the marts the Power BI report reads to exports/*.csv.
"""
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
COMPILED = ROOT / "target" / "compiled" / "bank_analytics" / "analyses"
DOC = ROOT / "docs" / "business_questions.md"
EXPORTS = ROOT / "exports"
POWERBI_TABLES = ["dim_date", "dim_districts", "dim_clients", "dim_accounts", "fct_loans", "rpt_monthly_kpis"]


def to_markdown(rel: duckdb.DuckDBPyRelation) -> str:
    cols = rel.columns
    rows = rel.fetchall()
    fmt = lambda v: "" if v is None else (f"{v:,}" if isinstance(v, int) and abs(v) >= 10_000 else str(v))
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    con = duckdb.connect(str(ROOT / "data" / "bank.duckdb"), read_only=True)
    out = ["# Business questions", "",
           "Generated by `scripts/run_analyses.py` from the SQL in `analyses/`. Amounts in Czech koruna (CZK).", ""]
    for sql_file in sorted(COMPILED.glob("q*.sql")):
        sql = sql_file.read_text(encoding="utf-8")
        header = []
        for line in sql.splitlines():
            if not line.startswith("--"):
                break
            header.append(line.lstrip("- ").strip())
        title = " ".join(header)
        out += [f"## {title}", "", f"SQL: [`analyses/{sql_file.name}`](../analyses/{sql_file.name})", "",
                to_markdown(con.sql(sql)), ""]
    DOC.parent.mkdir(exist_ok=True)
    DOC.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")

    EXPORTS.mkdir(exist_ok=True)
    for table in POWERBI_TABLES:
        path = EXPORTS / f"{table}.csv"
        con.sql(f"copy (select * from main_marts.{table}) to '{path.as_posix()}' (header, delimiter ',')")
        print(f"exported {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
